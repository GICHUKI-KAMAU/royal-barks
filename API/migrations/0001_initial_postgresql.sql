CREATE OR REPLACE FUNCTION prevent_active_admin_suspension()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.account_status = 'ACTIVE'
     AND NEW.account_status <> 'ACTIVE'
     AND EXISTS (
       SELECT 1
       FROM role_assignments
       WHERE profile_id = OLD.id AND role = 'ADMIN'
     ) THEN
    RAISE EXCEPTION 'Transfer Admin role before suspending this account';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS prevent_admin_suspension ON profiles;
CREATE TRIGGER prevent_admin_suspension
BEFORE UPDATE OF account_status ON profiles
FOR EACH ROW EXECUTE FUNCTION prevent_active_admin_suspension();

CREATE TABLE IF NOT EXISTS chama_cycles (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  expected_start_date TEXT NOT NULL,
  expected_end_date TEXT NOT NULL,
  first_payout_date TEXT NOT NULL,
  opt_in_deadline TEXT NOT NULL,
  min_seats INTEGER NOT NULL CHECK (min_seats > 0),
  max_seats INTEGER NOT NULL CHECK (max_seats >= min_seats),
  duration_months INTEGER NOT NULL CHECK (duration_months > 0),
  monthly_amount_per_seat DOUBLE PRECISION CHECK (monthly_amount_per_seat IS NULL OR monthly_amount_per_seat > 0),
  state TEXT NOT NULL CHECK (state IN ('DRAFT', 'OPT_IN_OPEN', 'OPT_IN_CLOSED', 'CARD_PICKING_OPEN', 'CARD_PICKING_CLOSED', 'RESULTS_REVEALED', 'PAYOUTS_IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
  created_by BIGINT NOT NULL REFERENCES profiles(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

